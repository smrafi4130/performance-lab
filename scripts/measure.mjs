// Reproducible performance measurement.
// Builds both apps, serves the production output, and runs Lighthouse (mobile
// profile) against each page several times, recording the MEDIAN run so a single
// noisy sample can't skew the story. Writes benchmarks/{slow,fast}.json and a
// benchmarks/summary.md table. Run with: pnpm build && pnpm measure
import { execSync } from "node:child_process";
import { createServer } from "node:http";
import { readFileSync, writeFileSync, statSync, readdirSync } from "node:fs";
import { extname, join } from "node:path";
import { launch } from "chrome-launcher";
import lighthouse from "lighthouse";

const DIST = "dist";
const PORT = 4195;
const RUNS = Number(process.env.RUNS ?? 5);
const CHROME_PATH =
  process.env.CHROME_PATH || "/opt/pw-browsers/chromium-1243/chrome-linux64/chrome";

const MIME = {
  ".html": "text/html",
  ".js": "text/javascript",
  ".css": "text/css",
  ".json": "application/json",
  ".svg": "image/svg+xml",
};

function serve() {
  return createServer((req, res) => {
    const url = (req.url ?? "/").split("?")[0];
    const path = join(DIST, url === "/" ? "index.html" : url.slice(1));
    try {
      const body = readFileSync(path);
      res.writeHead(200, { "Content-Type": MIME[extname(path)] ?? "application/octet-stream" });
      res.end(body);
    } catch {
      res.writeHead(404).end("not found");
    }
  }).listen(PORT);
}

const median = (xs) => {
  const s = [...xs].sort((a, b) => a - b);
  const m = Math.floor(s.length / 2);
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
};

async function measure(port, page) {
  const runs = [];
  for (let i = 0; i < RUNS; i++) {
    const { lhr } = await lighthouse(`http://localhost:${PORT}/${page}`, {
      port,
      onlyCategories: ["performance"],
      formFactor: "mobile",
      screenEmulation: {
        mobile: true,
        width: 412,
        height: 823,
        deviceScaleFactor: 1.75,
        disabled: false,
      },
      throttling: { rttMs: 150, throughputKbps: 1638, cpuSlowdownMultiplier: 4 },
    });
    const a = lhr.audits;
    const jsBytes = (a["network-requests"].details?.items ?? [])
      .filter((it) => it.mimeType?.includes("javascript"))
      .reduce((sum, it) => sum + (it.transferSize ?? 0), 0);
    runs.push({
      score: Math.round(lhr.categories.performance.score * 100),
      fcp: a["first-contentful-paint"].numericValue,
      lcp: a["largest-contentful-paint"].numericValue,
      tbt: a["total-blocking-time"].numericValue,
      si: a["speed-index"].numericValue,
      jsBytes,
    });
  }
  const pick = (k) => Math.round(median(runs.map((r) => r[k])));
  return {
    page,
    runs: RUNS,
    score: pick("score"),
    fcp: pick("fcp"),
    lcp: pick("lcp"),
    tbt: pick("tbt"),
    si: pick("si"),
    jsBytes: pick("jsBytes"),
  };
}

function initialJsBytes(entry) {
  // Sum the entry chunk + its static imports from the Vite manifest (excludes
  // lazy/dynamic chunks), using gzip-less raw bytes from disk.
  const manifest = JSON.parse(readFileSync(join(DIST, ".vite/manifest.json"), "utf8"));
  const node = manifest[entry];
  const files = new Set([node.file, ...(node.imports ?? []).map((k) => manifest[k].file)]);
  let bytes = 0;
  for (const f of files) bytes += statSync(join(DIST, f)).size;
  return bytes;
}

const server = serve();
const chrome = await launch({
  chromePath: CHROME_PATH,
  chromeFlags: ["--headless", "--no-sandbox", "--disable-gpu"],
});
try {
  const slow = await measure(chrome.port, "slow.html");
  const fast = await measure(chrome.port, "fast.html");
  slow.initialJs = initialJsBytes("slow.html");
  fast.initialJs = initialJsBytes("fast.html");
  writeFileSync("benchmarks/slow.json", JSON.stringify(slow, null, 2));
  writeFileSync("benchmarks/fast.json", JSON.stringify(fast, null, 2));

  const ms = (n) => `${(n / 1000).toFixed(2)} s`;
  const kb = (n) => `${(n / 1024).toFixed(1)} kB`;
  const pct = (a, b) => `${Math.round((1 - b / a) * 100)}%`;
  const row = (label, fmt, key, lower = true) =>
    `| ${label} | ${fmt(slow[key])} | ${fmt(fast[key])} | ${lower ? pct(slow[key], fast[key]) + " lower" : "+" + (fast[key] - slow[key]) + " pts"} |`;
  const table = [
    `<!-- Generated by scripts/measure.mjs. Median of ${RUNS} Lighthouse runs, mobile profile (4x CPU, Slow 4G). -->`,
    "| Metric | Naive | Optimized | Improvement |",
    "| --- | ---: | ---: | ---: |",
    `| Performance score | ${slow.score} | ${fast.score} | +${fast.score - slow.score} pts |`,
    row("Largest Contentful Paint", ms, "lcp"),
    row("Total Blocking Time", ms, "tbt"),
    row("Speed Index", ms, "si"),
    row("First Contentful Paint", ms, "fcp"),
    `| Initial JS (uncompressed) | ${kb(slow.initialJs)} | ${kb(fast.initialJs)} | ${pct(slow.initialJs, fast.initialJs)} smaller |`,
    `| JS transferred (Lighthouse) | ${kb(slow.jsBytes)} | ${kb(fast.jsBytes)} | ${pct(slow.jsBytes, fast.jsBytes)} smaller |`,
    "",
  ].join("\n");
  writeFileSync("benchmarks/summary.md", table);
  console.log(table);
} finally {
  await chrome.kill();
  server.close();
}
